enum ContainerSize {
  /// Wąski (420px) - standard dla Logowania / Rejestracji
  narrow,

  /// Formularzowy (550px) - idealny balans dla rozbudowanych formularzy
  form,

  /// Średni (750px) - standardowy widok ustawień, profili
  medium,

  /// Czytelny (900px) - optymalna szerokość dla artykułów, treści tekstowych
  reading,

  /// Szeroki (1150px) - tabele, dashboardy, listy dokumentów
  wide,

  /// Pełny (Infinity) - mapy, edytory zdjęć, widok kamery
  full,
}
